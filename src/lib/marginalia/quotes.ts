export function findMarginaliaQuote(id: string) {
  return MARGINALIA_QUOTES.find((quote) => quote.id === id) ?? MARGINALIA_QUOTES[0];
}

export function randomMarginaliaQuoteId(random: () => number = Math.random) {
  const index = Math.min(
    MARGINALIA_QUOTES.length - 1,
    Math.floor(Math.max(0, random()) * MARGINALIA_QUOTES.length),
  );
  return MARGINALIA_QUOTES[index].id;
}

export function nextMarginaliaQuoteId(currentId: string, random: () => number = Math.random) {
  if (MARGINALIA_QUOTES.length < 2) return MARGINALIA_QUOTES[0].id;

  const currentIndex = Math.max(
    0,
    MARGINALIA_QUOTES.findIndex((quote) => quote.id === currentId),
  );
  const offset = 1 + Math.floor(Math.max(0, random()) * (MARGINALIA_QUOTES.length - 1));
  return MARGINALIA_QUOTES[(currentIndex + Math.min(offset, MARGINALIA_QUOTES.length - 1)) % MARGINALIA_QUOTES.length].id;
}
